import SwiftTerm

enum TerminalPalette {
    private static func c(_ r: UInt16, _ g: UInt16, _ b: UInt16) -> Color {
        Color(red: r * 257, green: g * 257, blue: b * 257)
    }

    static let colors: [Color] = [
        // Normal (0–7)
        c(0x00, 0x00, 0x00), // black
        c(0xCC, 0x00, 0x00), // red
        c(0x00, 0xCC, 0x00), // green
        c(0xCC, 0xCC, 0x00), // yellow
        c(0x00, 0x00, 0xCC), // blue
        c(0xCC, 0x00, 0xCC), // magenta
        c(0x00, 0xCC, 0xCC), // cyan
        c(0xE5, 0xE5, 0xE5), // white
        // Bright (8–15)
        c(0x7F, 0x7F, 0x7F), // bright black
        c(0xFF, 0x00, 0x00), // bright red
        c(0x00, 0xFF, 0x00), // bright green
        c(0xFF, 0xFF, 0x00), // bright yellow
        c(0x5C, 0x5C, 0xFF), // bright blue
        c(0xFF, 0x00, 0xFF), // bright magenta
        c(0x00, 0xFF, 0xFF), // bright cyan
        c(0xFF, 0xFF, 0xFF), // bright white
    ]
}
