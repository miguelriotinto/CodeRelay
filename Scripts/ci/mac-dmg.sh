#!/bin/bash
# Builds Code[Relay] for Mac as a notarized, stapled DMG for direct download
# (releases of miguelriotinto/coderelay-app), next to the App Store /
# TestFlight build. Run by the macos-dmg job in apple-release.yml with the
# build number just uploaded; also the break-glass path on a Mac whose login
# keychain holds the Developer ID Application identity.
#
#   Scripts/ci/mac-dmg.sh <build-number> <out.dmg>
#
# Needs: ASC_KEY_PATH / ASC_KEY_ID / ASC_ISSUER_ID (notarytool authenticates
# with the App Store Connect API key), a "Developer ID Application" identity in
# a keychain on the search list, and an Xcode project generated by xcodegen.
#
# Why it signs by hand instead of `xcodebuild -exportArchive -method developer-id`:
# cloud signing refuses Developer ID with our API key ("Cloud signing
# permission error"), so the archive is built UNSIGNED and signed here with the
# team's Developer ID certificate, the way Code[Whisper]'s tools/release.sh does.
set -euo pipefail

BUILD=${1:?build number}
OUT=${2:?output .dmg path}
: "${ASC_KEY_PATH:?}" "${ASC_KEY_ID:?}" "${ASC_ISSUER_ID:?}"

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
PROFILE="$ROOT/packaging/macos/CodeRelayMac-DeveloperID.provisionprofile"
TEAM=T9WF95GC9T
BUNDLE_ID=com.singular.coderelay.mac
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

IDENTITY=$(security find-identity -v -p codesigning | grep '"Developer ID Application: .*('"$TEAM"')"' | grep -v REVOKED | awk 'NR==1{print $2}')
[ -n "$IDENTITY" ] || { echo "no Developer ID Application identity for team $TEAM in the keychain"; exit 1; }
[ -f "$PROFILE" ] || { echo "missing $PROFILE"; exit 1; }

echo "== archive (unsigned, hardened runtime), build $BUILD"
# Notarization requires the hardened runtime; it is turned on for this build
# only, so the App Store archive stays exactly as before.
xcodebuild archive \
  -project "$ROOT/CodeRelay.xcodeproj" -scheme CodeRelayMac -configuration Release \
  -destination 'generic/platform=macOS' -archivePath "$WORK/app.xcarchive" \
  -skipMacroValidation \
  CODE_SIGNING_ALLOWED=NO CODE_SIGNING_REQUIRED=NO CODE_SIGN_IDENTITY= \
  ENABLE_HARDENED_RUNTIME=YES CURRENT_PROJECT_VERSION="$BUILD" > "$WORK/archive.log" 2>&1 \
  || { tail -40 "$WORK/archive.log"; exit 1; }
APP_SRC=$(find "$WORK/app.xcarchive/Products/Applications" -maxdepth 1 -name '*.app' | head -1)
[ -n "$APP_SRC" ] || { echo "no .app in the archive"; exit 1; }
NAME=$(basename "$APP_SRC")

mkdir -p "$WORK/disk"
APP="$WORK/disk/$NAME"
cp -R "$APP_SRC" "$APP"
GOT=$(/usr/libexec/PlistBuddy -c "Print :CFBundleVersion" "$APP/Contents/Info.plist")
[ "$GOT" = "$BUILD" ] || { echo "CFBundleVersion $GOT != $BUILD"; exit 1; }

echo "== entitlements"
# The same set the App Store build is signed with: the project's entitlements
# plus the app and team identifiers the profile grants. Push takes the value
# the Developer ID profile grants, `production` — the project file carries
# `development` for Xcode's own builds, and a signed value the embedded profile
# does not grant makes macOS refuse to launch the app. (Older trees used the iOS
# key `aps-environment`, which macOS ignores; either is replaced.)
ENT="$WORK/app.entitlements"
cp "$ROOT/CodeRelayMac/CodeRelayMac.entitlements" "$ENT"
/usr/libexec/PlistBuddy -c "Delete :aps-environment" "$ENT" 2>/dev/null || true
/usr/libexec/PlistBuddy -c "Delete :com.apple.developer.aps-environment" "$ENT" 2>/dev/null || true
/usr/libexec/PlistBuddy -c "Add :com.apple.developer.aps-environment string production" "$ENT"
/usr/libexec/PlistBuddy -c "Add :com.apple.application-identifier string $TEAM.$BUNDLE_ID" "$ENT"
/usr/libexec/PlistBuddy -c "Add :com.apple.developer.team-identifier string $TEAM" "$ENT"

echo "== sign the app (Developer ID, hardened runtime)"
cp "$PROFILE" "$APP/Contents/embedded.provisionprofile"
codesign --force --options runtime --timestamp --entitlements "$ENT" --sign "$IDENTITY" "$APP"
codesign --verify --strict --deep --verbose=2 "$APP"

notarize() {
  xcrun notarytool submit "$1" --key "$ASC_KEY_PATH" --key-id "$ASC_KEY_ID" --issuer "$ASC_ISSUER_ID" \
    --wait --output-format json > "$WORK/notary.json"
  STATUS=$(/usr/bin/python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["status"])' "$WORK/notary.json")
  ID=$(/usr/bin/python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["id"])' "$WORK/notary.json")
  echo "notarization $ID: $STATUS"
  if [ "$STATUS" != "Accepted" ]; then
    xcrun notarytool log "$ID" --key "$ASC_KEY_PATH" --key-id "$ASC_KEY_ID" --issuer "$ASC_ISSUER_ID" || true
    exit 1
  fi
}

echo "== notarize + staple the app"
# Stapled to the app as well as the DMG, so a copy dragged to /Applications
# opens offline on first launch too.
ditto -c -k --keepParent "$APP" "$WORK/app.zip"
notarize "$WORK/app.zip"
xcrun stapler staple "$APP"

echo "== DMG (designed Finder window)"
"$ROOT/Scripts/ci/make-dmg.sh" "$APP" "$OUT" "Code[Relay]"
codesign --force --timestamp --sign "$IDENTITY" "$OUT"
notarize "$OUT"
xcrun stapler staple "$OUT"

echo "== verify"
spctl --assess --type open --context context:primary-signature -v "$OUT"
MOUNT=$(hdiutil attach -nobrowse -readonly -noautoopen "$OUT" | awk -F'\t' '/\/Volumes\//{print $NF}')
spctl --assess --type execute -v "$MOUNT/$NAME"
xcrun stapler validate "$MOUNT/$NAME"
hdiutil detach -quiet "$MOUNT"
echo "wrote $OUT"
